export function getProfile(profileId) {
  return PAU_PROFILES[profileId] || PAU_PROFILES[DEFAULT_PROFILE_ID];
}

export function createEmptyResponses(criteria) {
  return Object.fromEntries(criteria.map((criterion) => [criterion.id, ""]));
}

export function getMaximumScore(criteria) {
  return criteria.reduce((total, criterion) => total + criterion.max, 0);
}
